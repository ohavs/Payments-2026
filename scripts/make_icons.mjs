// Launcher and web icons for every palette, from src/lib/app-icons.js.
// Android: adaptive layers (background with its texture, the ₪ sticker in
// front; the monochrome ₪ layer is shared) and legacy icons for Android 7.
// "green" keeps the plain ic_launcher names; the others are ic_launcher_<id>,
// used by the activity-aliases in AndroidManifest.xml. Web: the green one.
// Usage: node scripts/make_icons.mjs   (from the repo root; uses the e2e Playwright)
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { PALETTES, iconSvg } from '../src/lib/app-icons.js';

const { chromium } = createRequire(new URL('../e2e/package.json', import.meta.url))('playwright');
const RES = 'android/app/src/main/res';
const ADAPTIVE = { mdpi: 108, hdpi: 162, xhdpi: 216, xxhdpi: 324, xxxhdpi: 432 };
const LEGACY = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 512, height: 512 } });

// svg inside a box of size px, clipped to radius (px or a CSS value).
async function render(path, svg, size, radius = 0) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<html><body style="margin:0;background:transparent">
    <div style="width:${size}px;height:${size}px;overflow:hidden;border-radius:${radius}">${svg}</div></body></html>`);
  writeFileSync(path, await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } }));
}

const adaptiveXml = (name) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_icons.mjs -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/${name}_background"/>
    <foreground android:drawable="@mipmap/${name}_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`;

for (const { id } of PALETTES) {
  const name = id === 'green' ? 'ic_launcher' : `ic_launcher_${id}`;
  for (const [dens, n] of Object.entries(ADAPTIVE)) {
    mkdirSync(`${RES}/mipmap-${dens}`, { recursive: true });
    await render(`${RES}/mipmap-${dens}/${name}_background.png`, iconSvg(id, { size: n, layer: 'bg', full: true }), n);
    await render(`${RES}/mipmap-${dens}/${name}_foreground.png`, iconSvg(id, { size: n, layer: 'fg', full: true }), n);
  }
  for (const [dens, n] of Object.entries(LEGACY)) {
    await render(`${RES}/mipmap-${dens}/${name}.png`, iconSvg(id, { size: n }), n, '22%');
    await render(`${RES}/mipmap-${dens}/${name}_round.png`, iconSvg(id, { size: n }), n, '50%');
  }
  writeFileSync(`${RES}/mipmap-anydpi-v26/${name}.xml`, adaptiveXml(name));
  writeFileSync(`${RES}/mipmap-anydpi-v26/${name}_round.xml`, adaptiveXml(name));
}

// Web (PWA): rounded where the platform doesn't mask, full bleed where it does.
await render('public/icons/favicon-32.png', iconSvg('green', { size: 32 }), 32, '22%');
await render('public/icons/icon-192.png', iconSvg('green', { size: 192 }), 192, '22%');
await render('public/icons/icon-512.png', iconSvg('green', { size: 512 }), 512, '22%');
await render('public/icons/apple-touch-icon.png', iconSvg('green', { size: 180 }), 180);
await render('public/icons/icon-maskable-512.png', iconSvg('green', { size: 512 }).replace('viewBox="18 18 72 72"', 'viewBox="12 12 84 84"'), 512);

await browser.close();
console.log('icons written');
